def upsert_knowledge(conn):
    for title, category, question, content, source, status in ARTICLES:
        row = conn.execute('SELECT id FROM knowledge WHERE title=?', (title,)).fetchone()
        if row:
            conn.execute(
                'UPDATE knowledge SET category=?, question=?, content=?, source=?, status=?, version=version+1, updated=CURRENT_TIMESTAMP WHERE id=?',
                (category, question, content, source, status, row[0]),
            )
        else:
            conn.execute(
                'INSERT INTO knowledge(title,category,question,content,source,status) VALUES (?,?,?,?,?,?)',
                (title, category, question, content, source, status),
            )
